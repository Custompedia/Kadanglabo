// Generates src/data/indonesiaMap.ts (coastline for the "Peta proyek" on /work).
// Source: Natural Earth 1:50m land (public domain):
//   https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_land.geojson
// usage: node scripts/build-map.mjs <ne_50m_land.geojson> [tolerance]
import fs from 'node:fs';

const [src, tolArg = '0.8'] = process.argv.slice(2);
const out = new URL('../src/data/indonesiaMap.ts', import.meta.url);
const BBOX = { w: 102.8, e: 117.0, n: -1.6, s: -9.3 };
const K = 100; // svg units per degree
const TOL = parseFloat(tolArg);
const W = Math.round((BBOX.e - BBOX.w) * K), H = Math.round((BBOX.n - BBOX.s) * K);
const project = ([lon, lat]) => [(lon - BBOX.w) * K, (BBOX.n - lat) * K];

// Sutherland–Hodgman against the bbox (in lon/lat)
function clipRing(ring) {
  const edges = [
    (p) => p[0] >= BBOX.w, (p) => p[0] <= BBOX.e, (p) => p[1] <= BBOX.n, (p) => p[1] >= BBOX.s,
  ];
  const inter = [
    (a, b) => { const t = (BBOX.w - a[0]) / (b[0] - a[0]); return [BBOX.w, a[1] + t * (b[1] - a[1])]; },
    (a, b) => { const t = (BBOX.e - a[0]) / (b[0] - a[0]); return [BBOX.e, a[1] + t * (b[1] - a[1])]; },
    (a, b) => { const t = (BBOX.n - a[1]) / (b[1] - a[1]); return [a[0] + t * (b[0] - a[0]), BBOX.n]; },
    (a, b) => { const t = (BBOX.s - a[1]) / (b[1] - a[1]); return [a[0] + t * (b[0] - a[0]), BBOX.s]; },
  ];
  let pts = ring;
  for (let e = 0; e < 4; e++) {
    const inside = edges[e]; const res = [];
    for (let i = 0; i < pts.length; i++) {
      const cur = pts[i], prev = pts[(i + pts.length - 1) % pts.length];
      const ci = inside(cur), pi = inside(prev);
      if (ci) { if (!pi) res.push(inter[e](prev, cur)); res.push(cur); }
      else if (pi) res.push(inter[e](prev, cur));
    }
    pts = res;
    if (!pts.length) break;
  }
  return pts;
}

// Douglas–Peucker on a closed ring (projected units)
function simplify(pts, tol) {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop(); let maxD = 0, idx = -1;
    const [ax, ay] = pts[a], [bx, by] = pts[b]; const dx = bx - ax, dy = by - ay; const len = Math.hypot(dx, dy) || 1e-9;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / len;
      if (d > maxD) { maxD = d; idx = i; }
    }
    if (maxD > tol && idx > 0) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

// closed ring: anchor at point 0 and the point farthest from it, simplify both halves
function simplifyRing(ring, tol) {
  let far = 0, best = -1;
  for (let i = 1; i < ring.length; i++) { const d = Math.hypot(ring[i][0] - ring[0][0], ring[i][1] - ring[0][1]); if (d > best) { best = d; far = i; } }
  const a = simplify(ring.slice(0, far + 1), tol);
  const b = simplify(ring.slice(far).concat([ring[0]]), tol);
  return a.concat(b.slice(1, -1));
}

const area = (pts) => { let s = 0; for (let i = 0; i < pts.length; i++) { const [x1, y1] = pts[i], [x2, y2] = pts[(i + 1) % pts.length]; s += x1 * y2 - x2 * y1; } return Math.abs(s / 2); };

const gj = JSON.parse(fs.readFileSync(src, 'utf8'));
const rings = [];
for (const f of gj.features) {
  const g = f.geometry; if (!g) continue;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [];
  for (const poly of polys) {
    for (const ring of poly) {
      let minX = 999, maxX = -999, minY = 999, maxY = -999;
      for (const [x, y] of ring) { if (x < minX) minX = x; if (x > maxX) maxX = x; if (y < minY) minY = y; if (y > maxY) maxY = y; }
      if (maxX < BBOX.w || minX > BBOX.e || maxY < BBOX.s || minY > BBOX.n) continue;
      const clipped = clipRing(ring.slice(0, -1));
      if (clipped.length < 3) continue;
      const proj = simplifyRing(clipped.map(project), TOL);
      if (proj.length < 3 || area(proj) < 18) continue; // drop specks (< ~0.0018 sq deg)
      rings.push(proj);
    }
  }
}
const r1 = (v) => Math.round(v * 10) / 10;
const d = rings.map((r) => 'M' + r.map(([x, y]) => `${r1(x)} ${r1(y)}`).join('L') + 'Z').join('');
const ts = `// Generated by scripts/build-map.mjs — Natural Earth 1:50m land (public domain), clipped & simplified.
export const MAP = { width: ${W}, height: ${H}, bbox: ${JSON.stringify(BBOX)} }

export const LAND = '${d}'

/** lon/lat -> position on the map in % (x from the left, y from the top) */
export const mapXY = (lon: number, lat: number) => ({
  x: ((lon - MAP.bbox.w) / (MAP.bbox.e - MAP.bbox.w)) * 100,
  y: ((MAP.bbox.n - lat) / (MAP.bbox.n - MAP.bbox.s)) * 100,
})
`;
fs.writeFileSync(out, ts);
console.log(`map: rings=${rings.length} points=${rings.reduce((s, r) => s + r.length, 0)} path=${(d.length / 1024).toFixed(1)}KB view=${W}x${H}`);
