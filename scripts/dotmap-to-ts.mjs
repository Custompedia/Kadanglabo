// Turns the dot grid from make-dotmap.py into src/data/dotMap.ts: one SVG path, each dot an "h0" with a round cap.
// Run: node scripts/dotmap-to-ts.mjs dots.json
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const d = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'))
const dots = d.dots.map(([x, y]) => `M${Math.round(x)} ${Math.round(y)}h0`).join('')
const ts = `// Generated by scripts/dotmap-to-ts.mjs from Natural Earth 1:10m land (public domain). Do not edit by hand.
// Box: lon ${d.lon0} to ${d.lon0 + d.w / d.k}, lat ${d.lat0} to ${d.lat0 - d.h / d.k}; ${d.k} svg units per degree.
export const DOT_MAP = { w: ${d.w}, h: ${d.h}, lon0: ${d.lon0}, lat0: ${d.lat0}, k: ${d.k} } as const
export const DOT_MAP_PATH =
  '${dots}'
`
fs.writeFileSync(path.join(root, 'src/data/dotMap.ts'), ts)
console.log(`src/data/dotMap.ts: ${d.dots.length} dots, ${dots.length} chars`)
